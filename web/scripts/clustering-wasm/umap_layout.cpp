size_t SerialWorkspaceBytes(int vertex_count, int edge_count) {
  if (vertex_count <= 0 || edge_count < 0) return 0;
  size_t total = 0;
  if (!AddArrayBytes(&total, static_cast<size_t>(edge_count), sizeof(double)) ||
      !AddArrayBytes(&total, static_cast<size_t>(edge_count), sizeof(double)) ||
      !AddArrayBytes(&total, static_cast<size_t>(edge_count), sizeof(double)) ||
      !AddArrayBytes(&total, static_cast<size_t>(vertex_count) * size_t{3},
                     sizeof(int64_t))) {
    return 0;
  }
  return total;
}

int OptimizeSerial(float* embedding, int vertex_count, int dimension,
                   const int32_t* head, const int32_t* tail,
                   const double* epochs_per_sample, int edge_count,
                   const int64_t rng_state[3], int epoch_count, double a,
                   double b, double gamma, double negative_sample_rate,
                   void* workspace, size_t workspace_bytes) {
  if (!ValidShape(vertex_count, dimension, edge_count) || embedding == nullptr ||
      rng_state == nullptr || epoch_count < 0 || !std::isfinite(a) ||
      !std::isfinite(b) || !std::isfinite(gamma) ||
      !std::isfinite(negative_sample_rate) || a <= 0.0 || b <= 0.0 ||
      gamma < 0.0 || negative_sample_rate <= 0.0 ||
      (edge_count > 0 &&
       (head == nullptr || tail == nullptr || epochs_per_sample == nullptr))) {
    return kInvalidArgument;
  }

  const size_t required = SerialWorkspaceBytes(vertex_count, edge_count);
  if (required == 0) return kSizeOverflow;
  if (workspace == nullptr || !IsWorkspaceAligned(workspace) ||
      workspace_bytes < required) {
    return kInsufficientWorkspace;
  }

  Workspace arena(workspace, workspace_bytes);
  double* epochs_per_negative_sample =
      arena.Allocate<double>(static_cast<size_t>(edge_count));
  double* epoch_of_next_negative_sample =
      arena.Allocate<double>(static_cast<size_t>(edge_count));
  double* epoch_of_next_sample =
      arena.Allocate<double>(static_cast<size_t>(edge_count));
  TauState* rng_state_per_sample =
      arena.Allocate<TauState>(static_cast<size_t>(vertex_count));
  if (epochs_per_negative_sample == nullptr ||
      epoch_of_next_negative_sample == nullptr ||
      epoch_of_next_sample == nullptr || rng_state_per_sample == nullptr) {
    return kInsufficientWorkspace;
  }

  for (int edge = 0; edge < edge_count; ++edge) {
    if (head[edge] < 0 || head[edge] >= vertex_count || tail[edge] < 0 ||
        tail[edge] >= vertex_count ||
        !std::isfinite(epochs_per_sample[edge]) ||
        epochs_per_sample[edge] <= 0.0) {
      return kInvalidArgument;
    }
    const double negative_epoch =
        epochs_per_sample[edge] / negative_sample_rate;
    epochs_per_negative_sample[edge] = negative_epoch;
    epoch_of_next_negative_sample[edge] = negative_epoch;
    epoch_of_next_sample[edge] = epochs_per_sample[edge];
  }

  for (int vertex = 0; vertex < vertex_count; ++vertex) {
    const float* row =
        embedding + static_cast<size_t>(vertex) * dimension;
    for (int coordinate = 0; coordinate < dimension; ++coordinate) {
      if (!std::isfinite(row[coordinate])) return kInvalidArgument;
    }
    const float first_coordinate = row[0];
    const int64_t coordinate_bits =
        std::bit_cast<int64_t>(static_cast<double>(first_coordinate));
    for (int state_index = 0; state_index < 3; ++state_index) {
      rng_state_per_sample[vertex].values[state_index] =
          WrappedAdd(rng_state[state_index], coordinate_bits);
    }
  }

  double alpha = 1.0;
  for (int epoch = 0; epoch < epoch_count; ++epoch) {
    for (int edge = 0; edge < edge_count; ++edge) {
      if (epoch_of_next_sample[edge] > static_cast<double>(epoch)) continue;

      const int head_index = head[edge];
      const int tail_index = tail[edge];
      float* current =
          embedding + static_cast<size_t>(head_index) * dimension;
      float* other = embedding + static_cast<size_t>(tail_index) * dimension;

      float distance_squared =
          ReducedSquaredDistance(current, other, dimension);
      const double positive_coefficient =
          PositiveGradientCoefficient(distance_squared, a, b);
      for (int coordinate = 0; coordinate < dimension; ++coordinate) {
        const float difference = current[coordinate] - other[coordinate];
        const double gradient =
            Clip(positive_coefficient * static_cast<double>(difference));
        current[coordinate] = static_cast<float>(
            static_cast<double>(current[coordinate]) + gradient * alpha);
        other[coordinate] = static_cast<float>(
            static_cast<double>(other[coordinate]) - gradient * alpha);
      }
      epoch_of_next_sample[edge] += epochs_per_sample[edge];

      const double negative_epoch = epochs_per_negative_sample[edge];
      const int64_t negative_sample_count = static_cast<int64_t>(
          (static_cast<double>(epoch) -
           epoch_of_next_negative_sample[edge]) /
          negative_epoch);
      for (int64_t sample = 0; sample < negative_sample_count; ++sample) {
        const int negative_tail =
            PositiveModulo(TauRandInt(&rng_state_per_sample[head_index]),
                           vertex_count);
        other = embedding + static_cast<size_t>(negative_tail) * dimension;
        distance_squared =
            ReducedSquaredDistance(current, other, dimension);

        if (!(distance_squared > 0.0f) && head_index == negative_tail) {
          continue;
        }
        const double negative_coefficient =
            NegativeGradientCoefficient(distance_squared, a, b, gamma);
        for (int coordinate = 0; coordinate < dimension; ++coordinate) {
          double gradient = 0.0;
          if (negative_coefficient > 0.0) {
            const float difference = current[coordinate] - other[coordinate];
            gradient = Clip(negative_coefficient *
                            static_cast<double>(difference));
          }
          current[coordinate] = static_cast<float>(
              static_cast<double>(current[coordinate]) + gradient * alpha);
        }
      }
      epoch_of_next_negative_sample[edge] +=
          static_cast<double>(negative_sample_count) * negative_epoch;
    }

    /*
     * This intentionally mirrors UMAP 0.5.12's end-of-epoch update. Epochs
     * zero and one therefore both execute with alpha == initial_alpha.
     */
    alpha = 1.0 - (static_cast<double>(epoch) /
                   static_cast<double>(epoch_count));
  }
  return kSuccess;
}

