constexpr size_t kAlignment = 16;
constexpr uint64_t kUint32Mask = 0xffff'ffffULL;

bool CheckedAdd(size_t left, size_t right, size_t* result) {
  if (right > std::numeric_limits<size_t>::max() - left) return false;
  *result = left + right;
  return true;
}

bool CheckedMultiply(size_t left, size_t right, size_t* result) {
  if (left != 0 && right > std::numeric_limits<size_t>::max() / left) {
    return false;
  }
  *result = left * right;
  return true;
}

bool AlignSize(size_t value, size_t* result) {
  constexpr size_t mask = kAlignment - 1;
  if (value > std::numeric_limits<size_t>::max() - mask) return false;
  *result = (value + mask) & ~mask;
  return true;
}

bool AddArrayBytes(size_t* total, size_t count, size_t item_bytes) {
  size_t aligned = 0;
  size_t bytes = 0;
  if (!AlignSize(*total, &aligned) ||
      !CheckedMultiply(count, item_bytes, &bytes) ||
      !CheckedAdd(aligned, bytes, total)) {
    return false;
  }
  return true;
}

class Workspace {
 public:
  Workspace(void* data, size_t size)
      : data_(static_cast<uint8_t*>(data)), size_(size) {}

  template <typename T>
  T* Allocate(size_t count) {
    size_t aligned = 0;
    size_t bytes = 0;
    size_t end = 0;
    if (!AlignSize(cursor_, &aligned) ||
        !CheckedMultiply(count, sizeof(T), &bytes) ||
        !CheckedAdd(aligned, bytes, &end) || end > size_) {
      return nullptr;
    }
    cursor_ = end;
    return reinterpret_cast<T*>(data_ + aligned);
  }

 private:
  uint8_t* data_;
  size_t size_;
  size_t cursor_ = 0;
};

bool IsWorkspaceAligned(const void* workspace) {
  return (reinterpret_cast<uintptr_t>(workspace) & (kAlignment - 1)) == 0;
}

bool ValidShape(int vertex_count, int dimension, int edge_count) {
  if (vertex_count <= 0 || dimension <= 0 || edge_count < 0) return false;
  size_t ignored = 0;
  return CheckedMultiply(static_cast<size_t>(vertex_count),
                         static_cast<size_t>(dimension), &ignored) &&
         CheckedMultiply(static_cast<size_t>(edge_count), sizeof(double),
                         &ignored) &&
         CheckedMultiply(static_cast<size_t>(vertex_count), size_t{3},
                         &ignored);
}

/*
 * Match the vector reduction shape generated by LLVM for UMAP's float32
 * fast-math rdist loop on the native reference machine. Keeping sixteen
 * independent accumulators also exposes straightforward SIMD to WebAssembly.
 */
float ReducedSquaredDistance(const float* left, const float* right,
                             int dimension) {
  float accumulator0 = 0.0f;
  float accumulator1 = 0.0f;
  float accumulator2 = 0.0f;
  float accumulator3 = 0.0f;
  float accumulator4 = 0.0f;
  float accumulator5 = 0.0f;
  float accumulator6 = 0.0f;
  float accumulator7 = 0.0f;
  float accumulator8 = 0.0f;
  float accumulator9 = 0.0f;
  float accumulator10 = 0.0f;
  float accumulator11 = 0.0f;
  float accumulator12 = 0.0f;
  float accumulator13 = 0.0f;
  float accumulator14 = 0.0f;
  float accumulator15 = 0.0f;

  const int vector_end = dimension & ~15;
  int coordinate = 0;
  for (; coordinate < vector_end; coordinate += 16) {
    const float difference0 = left[coordinate] - right[coordinate];
    const float difference1 = left[coordinate + 1] - right[coordinate + 1];
    const float difference2 = left[coordinate + 2] - right[coordinate + 2];
    const float difference3 = left[coordinate + 3] - right[coordinate + 3];
    const float difference4 = left[coordinate + 4] - right[coordinate + 4];
    const float difference5 = left[coordinate + 5] - right[coordinate + 5];
    const float difference6 = left[coordinate + 6] - right[coordinate + 6];
    const float difference7 = left[coordinate + 7] - right[coordinate + 7];
    const float difference8 = left[coordinate + 8] - right[coordinate + 8];
    const float difference9 = left[coordinate + 9] - right[coordinate + 9];
    const float difference10 = left[coordinate + 10] - right[coordinate + 10];
    const float difference11 = left[coordinate + 11] - right[coordinate + 11];
    const float difference12 = left[coordinate + 12] - right[coordinate + 12];
    const float difference13 = left[coordinate + 13] - right[coordinate + 13];
    const float difference14 = left[coordinate + 14] - right[coordinate + 14];
    const float difference15 = left[coordinate + 15] - right[coordinate + 15];
    accumulator0 += difference0 * difference0;
    accumulator1 += difference1 * difference1;
    accumulator2 += difference2 * difference2;
    accumulator3 += difference3 * difference3;
    accumulator4 += difference4 * difference4;
    accumulator5 += difference5 * difference5;
    accumulator6 += difference6 * difference6;
    accumulator7 += difference7 * difference7;
    accumulator8 += difference8 * difference8;
    accumulator9 += difference9 * difference9;
    accumulator10 += difference10 * difference10;
    accumulator11 += difference11 * difference11;
    accumulator12 += difference12 * difference12;
    accumulator13 += difference13 * difference13;
    accumulator14 += difference14 * difference14;
    accumulator15 += difference15 * difference15;
  }

  const float lane0 =
      (accumulator12 + accumulator8) + (accumulator4 + accumulator0);
  const float lane1 =
      (accumulator13 + accumulator9) + (accumulator5 + accumulator1);
  const float lane2 =
      (accumulator14 + accumulator10) + (accumulator6 + accumulator2);
  const float lane3 =
      (accumulator15 + accumulator11) + (accumulator7 + accumulator3);
  float result = (lane0 + lane1) + (lane2 + lane3);

  const int lane_end = dimension & ~3;
  float tail0 = result;
  float tail1 = 0.0f;
  float tail2 = 0.0f;
  float tail3 = 0.0f;
  for (; coordinate < lane_end; coordinate += 4) {
    const float difference0 = left[coordinate] - right[coordinate];
    const float difference1 = left[coordinate + 1] - right[coordinate + 1];
    const float difference2 = left[coordinate + 2] - right[coordinate + 2];
    const float difference3 = left[coordinate + 3] - right[coordinate + 3];
    tail0 += difference0 * difference0;
    tail1 += difference1 * difference1;
    tail2 += difference2 * difference2;
    tail3 += difference3 * difference3;
  }
  result = (tail0 + tail1) + (tail2 + tail3);

  for (; coordinate < dimension; ++coordinate) {
    const float difference = left[coordinate] - right[coordinate];
    result += difference * difference;
  }
  return result;
}

double Clip(double value) {
  if (value > 4.0) return 4.0;
  if (value < -4.0) return -4.0;
  return value;
}

struct TauState {
  int64_t values[3];
};

static_assert(sizeof(TauState) == sizeof(int64_t) * 3);

int64_t ArithmeticShiftRight(uint64_t bits, int shift) {
  if ((bits & (uint64_t{1} << 63)) == 0) {
    return static_cast<int64_t>(bits >> shift);
  }
  const uint64_t fill = ~uint64_t{0} << (64 - shift);
  return std::bit_cast<int64_t>((bits >> shift) | fill);
}

int32_t TauRandInt(TauState* state) {
  const uint64_t original0 = static_cast<uint64_t>(state->values[0]);
  const uint64_t original1 = static_cast<uint64_t>(state->values[1]);
  const uint64_t original2 = static_cast<uint64_t>(state->values[2]);

  const uint64_t left0 = ((original0 & 4294967294ULL) << 12) & kUint32Mask;
  const uint64_t mixed0 = ((original0 << 13) & kUint32Mask) ^ original0;
  state->values[0] = std::bit_cast<int64_t>(
      left0 ^ static_cast<uint64_t>(ArithmeticShiftRight(mixed0, 19)));

  const uint64_t left1 = ((original1 & 4294967288ULL) << 4) & kUint32Mask;
  const uint64_t mixed1 = ((original1 << 2) & kUint32Mask) ^ original1;
  state->values[1] = std::bit_cast<int64_t>(
      left1 ^ static_cast<uint64_t>(ArithmeticShiftRight(mixed1, 25)));

  const uint64_t left2 = ((original2 & 4294967280ULL) << 17) & kUint32Mask;
  const uint64_t mixed2 = ((original2 << 3) & kUint32Mask) ^ original2;
  state->values[2] = std::bit_cast<int64_t>(
      left2 ^ static_cast<uint64_t>(ArithmeticShiftRight(mixed2, 11)));

  const uint32_t result_bits = static_cast<uint32_t>(
      static_cast<uint64_t>(state->values[0]) ^
      static_cast<uint64_t>(state->values[1]) ^
      static_cast<uint64_t>(state->values[2]));
  return std::bit_cast<int32_t>(result_bits);
}

int PositiveModulo(int32_t value, int divisor) {
  int result = value % divisor;
  if (result < 0) result += divisor;
  return result;
}

int64_t WrappedAdd(int64_t left, int64_t right) {
  return std::bit_cast<int64_t>(static_cast<uint64_t>(left) +
                                static_cast<uint64_t>(right));
}

double PositiveGradientCoefficient(float distance_squared, double a,
                                   double b) {
  if (!(distance_squared > 0.0f)) return 0.0;
  const double distance = static_cast<double>(distance_squared);
  double result =
      -2.0 * a * b * std::pow(distance, b - 1.0);
  result /= a * std::pow(distance, b) + 1.0;
  return result;
}

double NegativeGradientCoefficient(float distance_squared, double a, double b,
                                   double gamma) {
  if (!(distance_squared > 0.0f)) return 0.0;
  const double distance = static_cast<double>(distance_squared);
  double result = 2.0 * gamma * b;
  result /= (0.001 + distance) * (a * std::pow(distance, b) + 1.0);
  return result;
}

